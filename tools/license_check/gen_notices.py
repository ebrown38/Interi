"""Generates THIRD_PARTY_NOTICES.md from the copyright files vcpkg installs for each port.

Use --check in CI to fail when the committed file is out of date with the dependency set.
Exit codes: 0 = ok/written, 1 = --check found a stale file, 2 = input error.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_licenses import collect_port_licenses  # noqa: E402

HEADER = """# Third-Party Notices

Interi is licensed under the MIT License (see `LICENSE`). It uses the third-party components
below, each under its own license. This file is generated by `tools/license_check/gen_notices.py`
from the vcpkg dependency set; do not edit it by hand.
"""


def _is_vcpkg_helper(port: str) -> bool:
    # vcpkg-cmake, vcpkg-cmake-config, ...: build scripts that are never part of Interi binaries.
    return port.startswith("vcpkg-")


def generate_notices(installed_dir: Path) -> str:
    parts = [HEADER]
    for port, license_expr in sorted(collect_port_licenses(installed_dir).items()):
        if _is_vcpkg_helper(port):
            continue
        copyright_file = Path(installed_dir) / "share" / port / "copyright"
        if not copyright_file.exists():
            # Empty package (e.g. `pthreads` on POSIX): nothing is shipped, so there is nothing to attribute.
            # check_licenses.py still vets its license metadata.
            continue
        text = copyright_file.read_text(encoding="utf-8", errors="replace").strip()
        parts.append(f"\n## {port}\n\nLicense: {license_expr or 'NOASSERTION'}\n\n```text\n{text}\n```\n")
    return "".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--installed-dir", required=True, type=Path, help="vcpkg_installed/<triplet>")
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--check", action="store_true", help="verify --output is up to date instead of writing it")
    args = parser.parse_args(argv)

    if not collect_port_licenses(args.installed_dir):
        print(f"error: no vcpkg SPDX documents found under {args.installed_dir}", file=sys.stderr)
        return 2
    notices = generate_notices(args.installed_dir)
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != notices:
            print(f"{args.output} is out of date. Regenerate with:\n  python3 tools/license_check/gen_notices.py "
                  f"--installed-dir <vcpkg_installed/triplet> --output {args.output}", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(notices, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
